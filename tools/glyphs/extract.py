"""Extract the few SMuFL glyph outlines the app needs from Bravura into
src/notation/glyphs.ts.

Bravura is (c) Steinberg Media Technologies GmbH, SIL Open Font License 1.1
(see LICENSES/Bravura-OFL.txt). Only outlines are extracted; no font file ships.

Usage (one-off, not part of the build):
  python3 -m venv .venv && .venv/bin/pip install fonttools==4.60.1
  curl -sSfLO https://raw.githubusercontent.com/steinbergmedia/bravura/master/redist/otf/Bravura.otf
  .venv/bin/python tools/glyphs/extract.py Bravura.otf > src/notation/glyphs.ts
"""
import sys
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.boundsPen import BoundsPen

WANT = [('gClef', 0xE050), ('fClef', 0xE062), ('brace', 0xE000), ('noteheadWhole', 0xE0A2)]


def num(v):
    return ('%.1f' % v).rstrip('0').rstrip('.')


font = TTFont(sys.argv[1])
glyph_set = font.getGlyphSet()
cmap = font.getBestCmap()
print('// Generated by tools/glyphs/extract.py from the Bravura font')
print('// (c) Steinberg Media Technologies GmbH, SIL Open Font License 1.1 (LICENSES/Bravura-OFL.txt).')
print('// Do not edit by hand.')
print('//')
print('// Units: font units, %d per em. 1 staff space = 250 units.' % font['head'].unitsPerEm)
print('// The y axis points UP: draw with transform scale(k, -k) where k = staffSpace / 250.')
print('// Origins: gClef = the G4 line, fClef = the F3 line, noteheadWhole = left edge, vertical centre,')
print('// brace = bottom of the brace (it is 1000 units = 4 staff spaces tall at scale k).')
print()
print('export interface Glyph {')
print('  readonly d: string;')
print('  readonly advance: number;')
print('  readonly bounds: readonly [number, number, number, number];')
print('}')
print()
print('export const GLYPHS = {')
for name, cp in WANT:
    g = glyph_set[cmap[cp]]
    pen = SVGPathPen(glyph_set, ntos=num)
    g.draw(pen)
    bp = BoundsPen(glyph_set)
    g.draw(bp)
    b = ', '.join(num(x) for x in bp.bounds)
    print('  %s: {' % name)
    print("    d: '%s'," % pen.getCommands())
    print('    advance: %d,' % g.width)
    print('    bounds: [%s],' % b)
    print('  },')
print('} as const satisfies Record<string, Glyph>;')
